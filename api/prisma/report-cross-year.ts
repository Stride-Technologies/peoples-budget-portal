/**
 * Each year's book against the year before (specs/017 T071, FR-010): what a
 * book says the previous year came to (its "current year" column) beside that
 * year's own document. Derived, never stored, never a gate.
 *
 *   pnpm --filter api db:report:cross-year -- --from 2024 --to 2026
 *
 * Writes docs/design/cross-year-report.md.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { PrismaPg } from '@prisma/adapter-pg';
import 'dotenv/config';
import { Prisma, PrismaClient } from '../src/generated/prisma/index';
import { compareWithPrevious } from '../src/budget-documents/compare-previous';

const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL! }),
});
const arg = (n: string) => {
  const i = process.argv.indexOf(`--${n}`);
  return i >= 0 ? Number(process.argv[i + 1]) : undefined;
};
/** Whole pesos, grouped, from the decimal string: never through a float. */
const peso = (v: string | null) => {
  if (v === null) return '—';
  const [whole] = new Prisma.Decimal(v).toFixed(0).split('.');
  return `₱${whole.replace(/\B(?=(\d{3})+(?!\d))/g, ',')}`;
};

async function main() {
  const from = arg('from') ?? 2024;
  const to = arg('to') ?? 2026;
  const out = [
    '# Each year against the year before',
    '',
    `Generated by \`report-cross-year.ts\` on ${new Date().toISOString().slice(0, 10)} (specs/017 FR-010). ` +
      "A book's current-year column is its estimate of the year before; the year before's own document says what that " +
      'year was budgeted at. Lines are matched by office, chart account and city sub-code. A difference is information, ' +
      'not an error: the Sanggunian, supplemental budgets and realignments all move a year after its book is printed.',
    '',
  ];
  for (let fy = from; fy <= to; fy++) {
    const docs = await prisma.budgetDocument.findMany({
      where: { budgetCycle: { fiscalYear: fy } },
      select: { id: true, kind: true, status: true },
    });
    const doc =
      docs.find((d) => d.kind === 'ORDINANCE' && d.status === 'ENACTED') ??
      docs.find((d) => d.kind === 'LEP');
    if (!doc) continue;
    const c = await compareWithPrevious(prisma, doc.id);
    out.push(
      `## FY${fy} ${doc.kind === 'LEP' ? 'LEP' : 'Ordinance'} against FY${fy - 1}`,
      '',
    );
    if (!c.previous) {
      out.push(`FY${fy - 1} has no document.`, '');
      continue;
    }
    const prev = `FY${fy - 1} ${c.previous.kind === 'LEP' ? 'LEP' : 'Ordinance'}`;
    out.push(
      `${c.counts.matched} of ${c.counts.here} lines match a line in the ${prev} (which has ${c.counts.there}); ` +
        `${c.counts.equal} agree to the centavo, ${c.counts.differ} differ.`,
      '',
    );
    // By office, object lines only: the office's whole year moved by how much.
    const byOffice = new Map<
      string,
      { here: Prisma.Decimal; there: Prisma.Decimal; n: number }
    >();
    for (const r of c.rows.filter(
      (r) => r.kind === 'object' && r.delta !== null,
    )) {
      const o = byOffice.get(r.scope) ?? {
        here: new Prisma.Decimal(0),
        there: new Prisma.Decimal(0),
        n: 0,
      };
      o.here = o.here.plus(r.thisCurrentYear!);
      o.there = o.there.plus(r.previousBudgetYear!);
      o.n++;
      byOffice.set(r.scope, o);
    }
    const offices = [...byOffice].sort((a, b) =>
      b[1].here
        .minus(b[1].there)
        .abs()
        .comparedTo(a[1].here.minus(a[1].there).abs()),
    );
    if (offices.length) {
      out.push(
        `### Offices whose differing lines moved most`,
        '',
        `| Office | Lines that differ | FY${fy - 1} in this book | ${prev} | Difference |`,
        '|---|---:|---:|---:|---:|',
        ...offices
          .slice(0, 15)
          .map(
            ([o, v]) =>
              `| ${o} | ${v.n} | ${peso(v.here.toFixed(2))} | ${peso(v.there.toFixed(2))} | ${peso(v.here.minus(v.there).toFixed(2))} |`,
          ),
        '',
      );
    }
    out.push(
      '### Largest single differences',
      '',
      `| Line | Office | FY${fy - 1} in this book | ${prev} | Difference |`,
      '|---|---|---:|---:|---:|',
      ...c.rows
        .slice(0, 20)
        .map(
          (r) =>
            `| ${r.title} \`${r.code}\` | ${r.scope} | ${peso(r.thisCurrentYear)} | ${peso(r.previousBudgetYear)} | ${peso(r.delta)} |`,
        ),
      '',
    );
  }
  const path = resolve(__dirname, '../../docs/design/cross-year-report.md');
  writeFileSync(path, out.join('\n'));
  console.log(`report: docs/design/cross-year-report.md`);
}

main()
  .catch((e: unknown) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => void prisma.$disconnect());
