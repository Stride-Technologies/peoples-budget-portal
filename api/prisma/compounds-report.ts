/**
 * The compounds report (specs/020, decision #16): every phrase the budget's own
 * names use that contains a topic keyword or a label alias, so a reviewer can
 * decide whether the phrase means that topic ("flood control" does) or not
 * ("capacity building" is not infrastructure). Decisions go in
 * `prisma/data/explorer-compounds.json`; this only reads.
 *
 *   pnpm --filter api db:report:compounds [-- --out <file.md>]
 *
 * Reads row names only (public budget data). Phrases are learned per corpus
 * (program names, project/activity names, budget-book items) with the same
 * rule the word map uses (`src/explorer/phrases.ts`).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { PrismaPg } from '@prisma/adapter-pg';
import 'dotenv/config';
import { PrismaClient } from '../src/generated/prisma/index';
import {
  compoundPattern,
  learnPhrases,
  norm,
  termsOf,
  type Compound,
} from '../src/explorer/phrases';

const data = (f: string) =>
  JSON.parse(readFileSync(resolve(__dirname, 'data', f), 'utf8')) as unknown;

/** Every topic keyword pattern and label alias, as `kind:id` → test. */
export function triggers(): { id: string; test: (phrase: string) => boolean; as: string[] }[] {
  const topics = (data('explorer-topics.json') as { topics: { id: string; rules: [string, string][] }[] }).topics;
  type L = { id: string; aliases?: Record<string, string[]>; subs?: L[] };
  const labels = (data('explorer-labels.json') as { labels: L[] }).labels.flatMap((l) => [l, ...(l.subs ?? [])]);
  const out: { id: string; test: (p: string) => boolean; as: string[] }[] = [];
  for (const t of topics) {
    const res = t.rules.filter(([k]) => k === 'keyword').map(([, v]) => new RegExp(v, 'i'));
    if (res.length) out.push({ id: `topic:${t.id}`, test: (p) => res.some((r) => r.test(p)), as: [] });
  }
  for (const l of labels) {
    const as = Object.values(l.aliases ?? {}).flat().map((a) => norm(a).trim());
    if (!as.length) continue;
    const res = as.map((a) => compoundPattern(a));
    out.push({
      id: `label:${l.id}`,
      test: (p) => res.some((r) => { r.lastIndex = 0; return r.test(norm(p)); }),
      as,
    });
  }
  return out;
}

async function main() {
  const out = process.argv.includes('--out')
    ? process.argv[process.argv.indexOf('--out') + 1]
    : resolve(__dirname, '..', '..', 'docs', 'design', 'explorer-compounds-report.md');
  const prisma = new PrismaClient({
    adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL! }),
  });
  const corpora: Record<string, string[]> = {
    'AIP programs': (await prisma.$queryRawUnsafe<{ name: string }[]>(`select name from programs where deleted_at is null`)).map((r) => r.name),
    'AIP projects and activities': (await prisma.$queryRawUnsafe<{ name: string }[]>(`select name from project_activities`)).map((r) => r.name),
    'Budget book items': (await prisma.$queryRawUnsafe<{ name: string }[]>(`select name from budget_items`)).map((r) => r.name),
  };
  await prisma.$disconnect();

  const reviewed = data('explorer-compounds.json') as { compounds: Compound[] };
  const decided = new Map(reviewed.compounds.map((c) => [norm(c.phrase).trim(), c]));
  const ts = triggers();
  const lines: string[] = [];
  let candidates = 0;
  let open = 0;
  for (const [corpus, names] of Object.entries(corpora)) {
    if (!names.length) continue;
    const phrases = learnPhrases(names);
    const rows = new Map<string, number>();
    for (const n of names) for (const t of termsOf(n, phrases)) if (t.includes(' ')) rows.set(t, (rows.get(t) ?? 0) + 1);
    const hits = [...rows]
      .map(([p, n]) => ({ p, n, ids: ts.filter((t) => t.test(p) && !t.as.includes(p)).map((t) => t.id) }))
      .filter((h) => h.ids.length)
      .sort((a, b) => b.n - a.n || a.p.localeCompare(b.p));
    lines.push(`\n## ${corpus}\n\n${names.length} names, ${phrases.size} phrases learned, ${hits.length} contain a topic keyword or label alias.\n`);
    lines.push('| Phrase | Rows | Would trigger | Reviewed |', '|---|---:|---|---|');
    for (const h of hits) {
      const d = decided.get(h.p);
      candidates++;
      if (!d) open++;
      lines.push(`| ${h.p} | ${h.n} | ${h.ids.join(', ')} | ${d ? (d.not.length ? `not ${d.not.join(', ')}` : 'means it') : '—'} |`);
    }
  }
  const head = `# Explorer compounds report

Generated by \`pnpm --filter api db:report:compounds\` on ${new Date().toISOString().slice(0, 10)} (specs/020, decision #16).

A phrase here contains a word a topic keyword or a label alias matches. If the phrase does
**not** mean that topic or label ("capacity building" is not infrastructure), add it to
\`api/prisma/data/explorer-compounds.json\` with the ids in \`not\`. If it does ("flood control" is
infrastructure), add it with \`not: []\` so it reads as reviewed. ${candidates} candidates, ${open} not yet reviewed.
`;
  writeFileSync(out, head + lines.join('\n') + '\n');
  console.log(`${candidates} candidates, ${open} not reviewed → ${out}`);
}

if (require.main === module) void main();
